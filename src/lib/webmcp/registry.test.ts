import { expect, it } from "vitest";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { loadTools, packLoaders } from "./registry";
import { assertSafeSchema, forbiddenIdentifier, toolNamePattern } from "./denylist";
import { destinations } from "./destinations";

const root = resolve(fileURLToPath(new URL("../../../", import.meta.url)));
function files(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}
it("explicit lazy index discovers every feature pack exactly once", () => {
  expect(Object.keys(packLoaders).sort()).toEqual(files(`${root}/src`)
    .filter(path => path.endsWith(".webmcp.ts")).map(path => path.slice(root.length + 1)).sort());
});
it("enforces read-only architecture, schema budgets and existing page placements", async () => {
  const tools = await loadTools();
  const routes = files(`${root}/src/app`).filter(path => path.endsWith("/page.tsx"))
    .map(path => path.slice(`${root}/src/app`.length, -"/page.tsx".length).replace(/\/\([^/]+\)/g, "") || "/");
  for (const tool of tools) {
    expect(tool.name).toMatch(toolNamePattern);
    expect(tool.name.length).toBeLessThanOrEqual(40);
    expect(forbiddenIdentifier.test(tool.name)).toBe(false);
    expect(tool.description.length).toBeLessThanOrEqual(500);
    expect(tool.risk).toBe("read");
    assertSafeSchema(z.toJSONSchema(tool.inputSchema, { io: "input" }));
    expect(tool.placement).toBeDefined();
    if (tool.placement === "global") expect(tool.name.startsWith("site_")).toBe(true);
    else for (const route of tool.placement!.routes) expect(routes).toContain(typeof route === "string" ? route : route.path);
  }
  for (const destination of destinations) expect(routes).toContain(destination.path);
  for (const path of Object.keys(packLoaders)) {
    const source = readFileSync(`${root}/${path}`, "utf8");
    expect(source).not.toMatch(/\b(?:useMutation|useAction|fetch|mutation|action)\s*\(/);
    expect(source).not.toMatch(/api\.[\w.]+\.(?:mutations|actions)\b/);
  }
});
it("writes the project-owned tool inventory deterministically", async () => {
  const tools = (await loadTools()).sort((left, right) => left.name.localeCompare(right.name));
  const text = "# BikeFitBoost WebMCP tools\n\nGenerated by src/lib/webmcp/registry.test.ts. See [conventions](WEBMCP.md).\n\n" +
    "| Tool | Scope | Risk | Untrusted content | Placement | Returns |\n| --- | --- | --- | --- | --- | --- |\n" +
    tools.map(tool => `| ${tool.name} | ${tool.scope} | read | ${Boolean(tool.untrustedContent)} | ${tool.placement === "global" ? "global" :
      tool.placement!.routes.map(route => typeof route === "string" ? route : `${route.path}${route.prefix ? "/*" : ""}`).join(", ")} | ${tool.description} |`).join("\n") + "\n";
  const path = `${root}/docs/WEBMCP-TOOLS.md`;
  if (!existsSync(path) || readFileSync(path, "utf8") !== text) writeFileSync(path, text);
  expect(readFileSync(path, "utf8")).toBe(text);
});
